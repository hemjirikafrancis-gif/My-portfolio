        <h1 class="sp-title">WHETHER EMPLOYMENT OF FEMALE JUNIOR STAFFS TO WORK INCLUSIVE NIGHT SHIFTS CAN BE SAID TO BE LEGAL UNDER THE LABOUR ACT</h1>

        <div class="sp-content">
          <p>Female employees are considered <em>sui generis</em> employees, thereby classifying them as vulnerable due to their peculiar nature. This however is against Section 15(2) &amp; (3), 17(3) and 42 of the 1999 Nigerian Constitution (as amended) and Protocol to the African Charter on Human and Peoples' Right on the Right of Women in Africa, 2005, which states that females should be given equal opportunity as men in the working place.</p>

          <p>The C171 – Night Work Convention, 1990 (No. 171) provides for measures that need to be in place where there is a need for night shift work, though Nigeria has not ratified same.</p>

          <p>It is trite that <strong>Section 55(1) of the Labour Act</strong> provides that women in private or public industrial undertaking or agricultural undertaking cannot engage in manual labour overnight. Exceptions are nurses and women in non-manual labour managerial positions. See Section 55(2)(1) of the Labour Act.</p>

          <p>The employment of female junior staffs to work night shifts can only be allowed subject to certain conditions as stated by <strong>Section 55(5)</strong> of the Labour Act:</p>

          <ul class="sp-list">
            <li>There must be a collective bargaining agreement between the company and its workers union which shall spell out the agreement to allow women work night shifts and the adequate provision and protection in place for the women concerned.</li>
            <li>The Minister of Labour and Employment may by Order exclude the applicability of Section 55(1) to a company; this power is discretionary even when the above requirement is satisfied.</li>
          </ul>

          <h3 class="sp-heading">THE PROS AND CONS OF THIS APPROACH</h3>

          <p>Any company that adopts this approach is going to become one of the few companies bridging the gender gap, encouraging diversity within the industry, which is in agreement with Section 42 of the 1999 Nigerian Constitution (as amended).</p>

          <p>However, even if a company is desirous of taking this approach, the order of the Minister of Labour and Employment is required to exempt the company from liability. The penalty of not complying with Section 55(5) of the Labour Act in breach of Section 55(1) is a fine not exceeding ₦100 or imprisonment for a term not exceeding one month or both.</p>

          <p>Taking this approach could open the door to negative occurrences in the workplace, given the vulnerable nature of women. Unless strict measures are put in place, sexual harassment cases and associated vices could be witnessed. The point to bear in mind is that the Minister's approval is discretionary and can be revoked upon breach of the terms and conditions set — hence the necessity to insert a dispute resolution clause in the collective bargaining agreement.</p>

          <h3 class="sp-heading">WHETHER LARGE COMPANIES ARE ADOPTING THIS APPROACH</h3>

          <p>Instructive is the approval dated <strong>21st January, 2019</strong> granted by the Minister of Labour and Employment to <strong>APM Terminals, Apapa, Lagos</strong>. The approach APM Terminals took was to file the permit application accompanied with the collective bargaining agreement which contained sufficient physical provisions and a maternity policy.</p>

          <h3 class="sp-heading">THE COLLECTIVE BARGAINING AGREEMENT APPROACH</h3>

          <p>Pursuant to the Labour Act, normal working hours shall be fixed under any employment contract. Thus, working hours can be agreed on through collective bargaining within the organization or industry. The only available option to allow women to work night shifts as provided under Section 55(5) is through a collective bargaining agreement, which is a condition precedent for the grant of an Order by the Minister.</p>

          <p>This approach involves a written contract between a company and the union representing the company's employees, covering:</p>
          <ul class="sp-list">
            <li>Wages, employment conditions, working hours and benefits</li>
            <li>Union rights and responsibilities; management rights and responsibilities</li>
            <li>Grievance procedures and consequences for violation</li>
            <li>Measures for female employees' transportation and protection against harassment and abuses</li>
            <li>Maternity policy, number of hours per shift and number of shifts per week</li>
            <li>Room for amendment of the agreement</li>
          </ul>

          <p>See <em>A.C.B PLC v. Nbisike (1995) 8 NWLR (pt.416) 725; Nwajagwu v. British American Insurance Company Ltd. (2000) LPELR-107766 (CA)</em>.</p>

