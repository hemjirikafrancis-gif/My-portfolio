        <h1 class="sp-title">Implications of proposed criminalization of casualization and outlawing of outsourcing and its impact on Directors/Management teams.</h1>

        <div class="sp-content">
          <p>The National Assembly of The Federal Republic of Nigeria is considering a bill for the amendment of the Labour Act. The said bill follows:</p>

          <blockquote class="sp-bill">A BILL FOR AN ACT TO AMEND THE LABOUR ACT TO PROHIBIT AND CRIMINALISE CASUALIZATION OF WORKERS AFTER SIX MONTHS OF ENGAGEMENT BY EMPLOYERS IN NIGERIA, OUTSOURCING EMPLOYMENT IN CORE AREAS OF OPERATION AND FOR RELATED MATTERS.<br><em>Sponsored by Hon. Tasir Olawale Raji</em></blockquote>

          <p>ENACTED by the National Assembly of the Federal Republic of Nigeria, the Labour Act is hereby amended by creating new <strong>Section 8</strong>, which provides that every worker who has remained in employment for a period of not less than six months shall have his employment regularized as a full and permanent staff. Any employer who disengages such a worker without regularizing the employment shall pay to the worker full salary and all allowances due to a permanent staff for six months.</p>

          <p>Failure to comply is an offence. In the case of a natural person, the penalty is a fine not exceeding two million naira or imprisonment for two years or both. In the case of a corporate body, each director of the company shall be liable to imprisonment for two years or a fine not exceeding two million naira or both.</p>

          <p>The proposed <strong>Section 9</strong> prohibits outsourcing within a company's core aims and objectives of operation. Failure to comply makes the employer guilty of an offence carrying the same penalties above.</p>

          <h3 class="sp-heading">OPINION</h3>

          <p>What or who a casual worker is was defined in <em>OWENA MASS TRANSPORTATION CO. LTD v. OKONOGBO (2018) LPELR-45221(CA)</em>:</p>

          <blockquote class="sp-citation">"What then is a casual worker? It is one who has an explicit or implicit contract of employment which is not expected to continue for more than a short period… Legally, a casual employee is seen as a worker engaged for a period of less than 6 months and who is paid at the end of each day… Losses suffered by casual employees include abysmal low wages, absence of medical care allowances, no job security or promotion at work, no gratuity and other severance benefits, no leave or leave allowance, freedom of association which is often jeopardized, and no death benefits or accident insurance at work."</blockquote>

          <p>The proposed amendment <strong>does not make employing casual workers a criminal offence</strong>. For an offence to be committed, the employee must have been engaged for more than 6 months without the employment being regularised. Casual workers can still be engaged for periods less than 6 months.</p>

          <p>It appears that if a worker is engaged for repeated cycles of less than 6 months, no offence will have been committed, as long as the employment is terminated before 6 months and a fresh employment is created.</p>

          <p>With regards to outsourcing, this is prohibited only within a company's core aims and objectives. Core aims and objectives are determined by examining the memorandum and articles of association as filed with the Corporate Affairs Commission. As held in <em>CONTINENTAL CHEMISTS LTD v. IFEAKANDU (1966) LPELR-25293(SC)</em>, whatever is fairly incidental to the objects stated in the memorandum (unless expressly prohibited) is regarded as intra vires.</p>

          <h3 class="sp-heading">IMPACT ON DIRECTORS AND MANAGEMENT TEAM</h3>

          <p>The proposed amendment makes the directors of the company liable on conviction to a term of imprisonment. The Directors of the company will be the persons stated in form CO7 filed with the Corporate Affairs Commission or the persons held out by the company to the general public as a Director.</p>

          <p>As confirmed in <em>NWANKWO v. KAY-KAY CONSTRUCTION LTD (2014) LPELR-24336(CA)</em>, what determines if a person is a director is not whether their name is listed in Form C07 — if a person occupies that position by whatever name called, they are a director of the company.</p>

          <h3 class="sp-heading">SUMMARY</h3>
          <ul class="sp-list">
            <li>It is not an offence to engage casual workers; it only becomes an offence if they are engaged for more than 6 months.</li>
            <li>Casual workers may be engaged for repeated cycles of less than 6 months.</li>
            <li>Outsourcing has not been prohibited entirely — only outsourcing in core aims or objectives is sought to be prohibited.</li>
            <li>Directors and/or the company become liable for breach of terms of the Act.</li>
          </ul>

