        <h1 class="sp-title">Whether an employee who, in substance, is a manager but goes by the title "Director" can automatically exercise all the powers and enjoy the benefits of a director within the meaning of CAMA</h1>

        <div class="sp-content">
          <p><strong>Section 269(1) of CAMA 2020</strong> defines a director of a company registered under the Act as: <em>"Director of a company registered under this Act is a person duly appointed by the company to direct and manage the business of the company."</em></p>

          <p>Note that the definition states that such a director must be <strong>duly appointed</strong>. The methods of appointing a person to the office of director under the Act are laid out in Sections 272–274 as follows:</p>

          <ul class="sp-list">
            <li><strong>S.272 — First directors:</strong> The number of directors and names of first directors shall be determined in writing by the subscribers of the memorandum of association, or the directors may be named in the articles.</li>
            <li><strong>S.273(1) — By members:</strong> The members at the annual general meeting may re-elect or reject directors and appoint new ones.</li>
            <li><strong>S.274(1) — Casual vacancies:</strong> The Board of directors may appoint new directors to fill any casual vacancy arising out of death, resignation, retirement or removal.</li>
          </ul>

          <p>Anyone not appointed by any of the above means is <strong>not a director</strong> of the company within the meaning of the Act. This was confirmed in <em>LONGE v. FBN PLC (2010) LPELR-1793(SC)</em> and <em>OLOYEDE &amp; ORS v. ROBERTS &amp; ANOR (2015) LPELR-41001(CA)</em>, which make clear that the combined effect of these provisions leaves no doubt as to the mode and manner of appointing a director.</p>

          <p>Consequently, a person who is not a director within the meaning of CAMA is only a director by nomenclature and not by law. The powers and rights vested in a director by law will not accrue to such an individual.</p>

          <h3 class="sp-heading">WHERE THIRD PARTIES ARE CONCERNED</h3>

          <p>The case is different where third parties are involved. If a company holds out an employee as a director, the company may under certain circumstances be liable for the acts of that person. <strong>Section 269(2) of CAMA 2020</strong> provides:</p>

          <blockquote class="sp-citation">"There is a rebuttable presumption in favour of any person dealing with the company that all persons who are described by the company as directors, whether as executive or otherwise, is duly appointed."</blockquote>

          <p>In <em>NWANKWO v. KAY-KAY CONSTRUCTION LTD (2014) LPELR-24336(CA)</em>, the court held that what determines if a person is a director is not whether their name is listed in Form C07 at the Corporate Affairs Commission. If a person occupies that position by whatever name called, they are a director of the company.</p>

          <p>Some judicial decisions suggest that if a company has accorded an employee the rights, responsibility, position and privileges of a director, the company may be estopped from denying them as a director. The court will consider:</p>
          <ul class="sp-list">
            <li>Does the individual have any letter appointing them as a director duly executed by members of the board?</li>
            <li>Does the individual attend meetings of the board of directors?</li>
            <li>Does the person receive notices of meetings of the board of directors?</li>
          </ul>

          <p>Unless the above can be answered in the affirmative, the individual cannot exercise the powers or enjoy the privileges afforded to a director by CAMA.</p>

          <h3 class="sp-heading">NOTE ON DIRECTORS' DUTIES</h3>

          <p><strong>Sections 305(3) and 308 of CAMA</strong> require that every director shall exercise the powers and discharge the duties of their office honestly, in good faith, and in the best interests of the company. Even assuming a person were a validly appointed director, an action taken in violation of company policy cannot be described as being in the best interest of the company.</p>

          <h3 class="sp-heading">SUMMARY</h3>
          <ul class="sp-list">
            <li>A director within the meaning of the Act must be duly appointed.</li>
            <li>Without due process being followed in the appointment, the individual cannot invoke the provisions of the Act with regards to Directors.</li>
            <li>A company that holds out an individual as a director may be liable to third parties for the actions of that person, whether duly appointed or not.</li>
          </ul>

